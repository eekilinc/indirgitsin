// Composable helper
@androidx.compose.runtime.Composable
fun t(key: String): String {
    val lang = LocalAppLanguage.current
    return AppStrings.get(lang, key)
}
@androidx.compose.runtime.Composable
fun t(key: String, vararg args: Any): String {
    val lang = LocalAppLanguage.current
    return AppStrings.get(lang, key, *args)
}
