    fun get(lang: String, key: String): String = maps[lang]?.get(key) ?: tr[key] ?: key
    fun get(lang: String, key: String, vararg args: Any): String {
        val template = get(lang, key)
        return if (args.isEmpty()) template else try { String.format(template, *args) } catch (_: Exception) { template }
    }

